export interface AppState {
  root: TreeNode | null
  /** The right (clairvoyance) tree. Null until the first flip. Generated by
   * Bayes-reversal from the left tree, then FULLY EDITABLE and independent — no
   * further sync with the left. Persisted in the document (see document.ts). */
  rightRoot: TreeNode | null
  /** True once the right tree has been manually edited since its last
   * generation — drives the "edited since flip" deviation indicator and marks
   * VOC as a free comparison rather than strict clairvoyance. */
  rightEdited: boolean
  /** Last flip-generation error (unflippable structure), shown in the right
   * pane. Null when the last generation succeeded. */
  flipError: string | null
  selected: TreeNode | null
  message: string
  /** Split mode: shows the right (clairvoyance) tree beside the left. Entering
   * split regenerates the right tree from the left; both are then editable. */
  split: boolean
  /** 'ev' = risk-neutral expected value; 'eu' = certainty equivalent under
   * `utilityFn` (risk-adjusted). */
  displayMode: DisplayMode
  utilityFn: UtilityFunction
  view: ViewTransform
  viewRight: ViewTransform
  idCounter: number
  /** True when the tree/settings changed since the last save or load — used
   * to confirm before a load would discard unsaved work. */
  dirty: boolean
}

/** One undo/redo history entry: the full document as JSON (deep clone via the
 * tested serialize round-trip — now includes BOTH trees, the deviation flag and
 * split mode) plus the selected node id (which may live in either tree). */
interface Snapshot {
  json: string
  selectedId: string | null
}

