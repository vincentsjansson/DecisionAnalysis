  // ── Undo/redo history (snapshot-based) ──
  // `history[cursor]` is always the current committed state; earlier entries
  // are undo targets, later ones redo targets. A committed mutation sets
  // `pendingCommit`, and the tail of render() snapshots — so multi-node effects
  // (auto-fill, linked-group sync) that all finish before the single render()
  // collapse into ONE undo step. `restoring` suppresses that while we replay.
  const HISTORY_CAP = 100
  const history: Snapshot[] = []
  let cursor = -1
  let pendingCommit = false
  let restoring = false

  const markDirty = (): void => {
    state.dirty = true
    if (!restoring) pendingCommit = true
  }

  const guarded = (fn: () => void): void => {
    try {
      fn()
    } catch (e) {
      setMessage(e instanceof Error ? e.message : String(e))
    }
  }

  const incomingEdge = (node: TreeNode): { parent: TreeNode; edge: Outcome } | null => {
    if (!node.parent) return null
    const edge = node.parent.outcomes.find((o) => o.child === node)
    return edge ? { parent: node.parent, edge } : null
  }

  /** History token set for the path root -> `node` (the outcome labels taken
   * to reach it), so conditional probabilities resolve correctly for the
   * node's calculation trace. */
  const historyFor = (node: TreeNode): Set<string> => {
    const tokens: string[] = []
    let current = node
    for (let inc = incomingEdge(current); inc; inc = incomingEdge(current)) {
      tokens.push(branchLabel(inc.parent, inc.edge.label))
      current = inc.parent
    }
    return new Set(tokens)
  }

  const walkFind = (root: TreeNode | null, pred: (n: TreeNode) => boolean): TreeNode | null => {
    if (!root) return null
    const walk = (n: TreeNode): TreeNode | null => {
      if (pred(n)) return n
      for (const o of n.outcomes) {
        if (o.child) {
          const found = walk(o.child)
          if (found) return found
        }
      }
      return null
    }
    return walk(root)
  }

  /** Finds a node by id across BOTH trees — nodes can now live in either the
   * left or the (editable) right tree. */
  const nodeById = (id: string): TreeNode | null =>
    walkFind(state.root, (n) => n.id === id) ?? walkFind(state.rightRoot, (n) => n.id === id)

  /** The root of whichever tree owns `node` (left or right). Falls back to the
   * left root so existing left-only call sites are unaffected. Every mutation
   * routes its group-aware model call through this so it operates on the correct
   * tree, and so an edit to the right tree can be detected as a deviation. */
  const rootOf = (node: TreeNode): TreeNode => {
    if (state.rightRoot && walkFind(state.rightRoot, (n) => n === node)) return state.rightRoot
    return state.root ?? node
  }

  /** Marks the right tree as manually edited (deviated from its Bayes baseline)
   * when `node` belongs to it. Call from every right-tree mutation. */
  const touchTree = (node: TreeNode): void => {
    if (state.rightRoot && walkFind(state.rightRoot, (n) => n === node)) state.rightEdited = true
  }

  /** Same deviation check, keyed by an outcome edge (for payoff/probability
   * edits that only carry the edge, not its node). */
  const touchTreeByEdge = (edge: Outcome): void => {
    if (state.rightRoot && walkFind(state.rightRoot, (n) => n.outcomes.includes(edge))) {
      state.rightEdited = true
    }
  }

  /** After outcome(s) are added to a chance node that ALREADY has a following
   * child, extend the mirroring to the new (still-terminal) outcomes so they
   * get their own linked instance of that child variable — instead of being
   * left as leaves. E.g. a parent whose outcomes lead to nod'/nod'' gains a
   * nod''' under a newly-added outcome. Finds a template child anywhere in the
   * parent's linked group; no-op for decision parents (asymmetry is intentional)
   * or when no child exists yet. Returns the instances created. */
  const mirrorChildToNewOutcomes = (node: TreeNode): TreeNode[] => {
    if (node.nodeType !== 'chance') return []
    const owner = rootOf(node)
    let template: TreeNode | null = null
    for (const inst of [node, ...groupSiblings(owner, node)]) {
      const withChild = inst.outcomes.find((o) => o.child)
      if (withChild?.child) {
        template = withChild.child
        break
      }
    }
    if (!template) return []
    return mirrorLinkedInstances(owner, node, template, nextId)
  }

  /** Display form of a condition token "nodeId:label" -> "NodLabel = label". */
  const tokenDisplay = (token: string): string => {
    const sep = token.indexOf(':')
    const id = token.slice(0, sep)
    const label = token.slice(sep + 1)
    const node = nodeById(id)
    return `${node ? node.label : id} = ${label}`
  }

  /** Condition tokens available to `node`: only the ancestor outcomes actually
   * on this instance's path (root -> node). In a true tree each node instance
   * has exactly one path, so a condition on a *sibling* branch (e.g. "Väder =
   * Regn" for a node sitting under "Väder = Sol") can never match and would be a
   * dead row. Offering only reachable tokens keeps the conditional table honest;
   * cross-context authoring is expressed via the linked sibling instances, each
   * of which carries its own reachable path. (Legacy offered every ancestor
   * outcome because its flat-sequence nodes were shared across all paths.) */
  const availableTokens = (node: TreeNode): string[] => {
    const path: string[] = []
    for (let inc = incomingEdge(node); inc; inc = incomingEdge(inc.parent)) {
      path.push(branchLabel(inc.parent, inc.edge.label))
    }
    return path.reverse() // root-first for readable ordering
  }

  const currentDocument = (): DecisionDocument => ({
    tree: state.root,
    rightTree: state.rightRoot,
    rightEdited: state.rightEdited,
    split: state.split,
    displayMode: state.displayMode,
    utility: state.utilityFn,
    idCounter: state.idCounter,
  })

  const takeSnapshot = (): Snapshot => ({
    json: documentToJson(currentDocument()),
    selectedId: state.selected?.id ?? null,
  })

  /** Applies a deserialized document to live state (shared by restore + load). */
  const applyDocument = (doc: DecisionDocument): void => {
    state.root = doc.tree
    state.rightRoot = doc.rightTree
    state.rightEdited = doc.rightEdited
    state.split = doc.split
    state.displayMode = doc.displayMode
    state.utilityFn = doc.utility
    state.idCounter = doc.idCounter
  }

  const updateHistoryButtons = (): void => {
    undoBtn.disabled = cursor <= 0
    redoBtn.disabled = cursor >= history.length - 1
  }

  /** Records the current state as a new history entry, dropping any redo
   * future and capping the depth (oldest entries fall off silently). */
  const commitSnapshot = (): void => {
    history.length = cursor + 1 // drop the redo branch
    history.push(takeSnapshot())
    cursor++
    if (history.length > HISTORY_CAP) {
      history.shift()
      cursor--
    }
    updateHistoryButtons()
  }

  /** Establishes a fresh baseline (single entry, nothing to undo). Used at
   * startup and after loading a document — a load is a new baseline, not a
   * point in the previous document's history. */
  const resetHistory = (): void => {
    history.length = 0
    history.push(takeSnapshot())
    cursor = 0
    pendingCommit = false
    updateHistoryButtons()
  }

  const restore = (snap: Snapshot): void => {
    restoring = true
    try {
      applyDocument(deserializeDocument(snap.json))
      state.selected = snap.selectedId ? nodeById(snap.selectedId) : null
      state.dirty = true // restored state differs from the last saved file
      pendingCommit = false
      render()
    } finally {
      restoring = false
    }
    updateHistoryButtons()
  }

  const undo = (): void => {
    if (cursor <= 0) return
    cursor--
    restore(history[cursor])
  }

  const redo = (): void => {
    if (cursor >= history.length - 1) return
    cursor++
    restore(history[cursor])
  }

  /** (Re)generates the right (clairvoyance) tree from the left by Bayes
   * reversal. The left is always the source. Clears the deviation flag; on an
   * unflippable structure, stores the error and leaves no right tree. */
  const regenerateRight = (): void => {
    state.rightEdited = false
    if (!state.root) {
      state.rightRoot = null
      state.flipError = null
      return
    }
    try {
      state.rightRoot = reverseTreeWithBayes(state.root).flipped
      state.flipError = null
    } catch (e) {
      state.rightRoot = null
      state.flipError = e instanceof Error ? e.message : String(e)
    }
  }

  // ── API — every mutation goes through the model layer ──
  const api: AppApi = {
    createRoot(type, label) {
      const node = new TreeNode(nextId(), type, label)
      state.root = node
      state.selected = node
      setMessage('')
      markDirty()
      render()
      return node
    },

    addOutcomeTo(node, label, probability = NaN, value?) {
      const edge = addOutcomeToGroup(rootOf(node), node, label, probability, value)
      // If the node already has a following child, fill this new outcome with a
      // linked instance of it too (don't leave it a leaf).
      mirrorChildToNewOutcomes(node)
      touchTree(node)
      markDirty()
      render()
      return edge
    },

    attachChild(node, edge, type, label) {
      const owner = rootOf(node)
      const child = createLinkedNode(owner, nextId(), type, label)
      setChild(node, edge, child)
      state.selected = child
      touchTree(node)
      markDirty()
      // Proactively grow the same variable across the whole grid of positions
      // that should hold it: the parent's other terminal outcomes AND — when
      // the parent itself is a linked instance — the corresponding outcomes on
      // its sibling instances, all joining one linked group. Only under chance
      // parents: a chance variable recurs across its contexts, whereas decision
      // alternatives are deliberately asymmetric (act vs. don't act), so
      // auto-filling them would fight the classic decision-tree shape.
      const autoFilled =
        node.nodeType === 'chance' ? mirrorLinkedInstances(owner, node, child, nextId) : []
      if (autoFilled.length > 0) {
        const shown = [child, ...autoFilled].slice(0, 6).map((n) => `"${displayName(n)}"`).join(', ')
        const more = autoFilled.length + 1 > 6 ? ` (+${autoFilled.length + 1 - 6} till)` : ''
        setMessage(
          `Länkade instanser skapade: ${shown}${more}. ` +
            `Utfallsuppsättning, nodtyp och sannolikheter synkas automatiskt ` +
            `(en instans med egen villkorstabell styr sina egna sannolikheter).`,
        )
      } else if (child.instanceIndex > 0) {
        setMessage(
          `Länkad till variabeln "${child.label}" — utfall synkas automatiskt ` +
            `mellan alla instanser (visas som "${displayName(child)}").`,
        )
      }
      render()
      return child
    },

    toggleType(node) {
      const next = node.nodeType === 'chance' ? 'decision' : 'chance'
      // Node type is a variable-group invariant — propagate to every linked
      // instance (frikopplade instances have their own variableId, untouched).
      setNodeTypeInGroup(rootOf(node), node, next)
      touchTree(node)
      markDirty()
      render()
    },

    renameNode(node, label) {
      // Renaming propagates to the whole variable group (locked decision A).
      renameVariable(rootOf(node), node, label)
      touchTree(node)
      markDirty()
      render()
    },

    unlinkVariable(node) {
      unlinkNode(rootOf(node), node)
      touchTree(node)
      setMessage(`"${displayName(node)}" är nu frikopplad — egen variabel, synkas inte längre.`)
      markDirty()
      render()
    },

    renameOutcomeOn(node, edge, newLabel) {
      renameOutcomeInGroup(rootOf(node), node, edge, newLabel)
      touchTree(node)
      markDirty()
      render()
    },

    removeOutcomeFrom(node, edge) {
      removeOutcomeFromGroup(rootOf(node), node, edge)
      touchTree(node)
      markDirty()
      render()
    },

    reorderLevels(panelRoot, upperDepth) {
      // Rebuilds the panel's tree with the two adjacent levels swapped (throws
      // FlipError on an invalid swap — caller guards). Replaces the tree in
      // place; new node ids mean the previous selection no longer resolves.
      const restructured = reorderAdjacentLevels(panelRoot, upperDepth, nextId)
      if (panelRoot === state.rightRoot) {
        state.rightRoot = restructured
        state.rightEdited = true
      } else {
        state.root = restructured
      }
      state.selected = null
      markDirty()
      render()
    },

    setProbability(edge, probability) {
      edge.probability = probability
      touchTreeByEdge(edge)
      markDirty()
      render()
    },

    setValue(edge, value) {
      edge.value = value
      touchTreeByEdge(edge)
      markDirty()
      render()
    },

    setConditionalTable(node, rows) {
      const hadTable = node.conditionalTable.length > 0
      node.conditionalTable = rows
      const root = rootOf(node)
      touchTree(node)
      if (rows.length === 0 && hadTable) {
        // Table removed -> rejoin flat-probability sync by adopting the group's
        // shared distribution from a no-table sibling.
        adoptGroupProbabilities(root, node)
      } else if (rows.length === 0) {
        // No table before or after: base-probability edits sync to the group.
        syncProbabilitiesFromNode(root, node)
      }
      // rows.length > 0: node is now context-driven and opts out of flat sync.
      markDirty()
      render()
    },

    deleteNode(node) {
      const inRight = !!(state.rightRoot && walkFind(state.rightRoot, (n) => n === node))
      const inc = incomingEdge(node)
      if (!inc) {
        if (inRight) state.rightRoot = null
        else state.root = null
      } else {
        detachChild(inc.edge)
      }
      if (inRight) state.rightEdited = true
      if (state.selected === node) state.selected = null
      markDirty()
      render()
    },

    applyBackwardFill(node, edge, targetProbability) {
      const result = backwardFill(rootOf(node), node, edge, targetProbability)
      touchTree(node)
      const parts = result.siblings.map(
        (s) => `${s.edge.label}: ${fmt(s.oldProbability)} → ${fmt(s.newProbability)}`,
      )
      setMessage(
        `Justerade P(${displayName(result.node)} → ${result.edge.label}): ` +
          `${fmt(result.oldProbability)} → ${fmt(result.newProbability)}` +
          (parts.length > 0 ? ` · syskon omskalade: ${parts.join(', ')}` : ''),
      )
      markDirty()
      render()
    },

    exportDocument() {
      const json = documentToJson(currentDocument())
      state.dirty = false // a successful save clears the unsaved-changes flag
      return json
    },

    loadDocument(text, opts) {
      // Validate first, so a broken file never triggers a discard prompt.
      const doc = deserializeDocument(text)
      if (!opts?.skipConfirm && state.root && state.dirty) {
        if (!confirmFn('Osparade ändringar går förlorade om du laddar en fil. Fortsätt?')) {
          return false
        }
      }
      // A load restores BOTH trees exactly as saved (no regeneration) — the
      // whole point of persisting the right tree is that hand edits survive.
      applyDocument(doc)
      state.selected = null
      state.flipError = null
      state.dirty = false
      render()
      // A load is a fresh baseline — you can't undo back into the previous
      // document's history (that would produce a meaningless hybrid state).
      resetHistory()
      return true
    },

    toggleSplit() {
      if (state.split) {
        // "Sammanfoga": leave split view. The right tree is kept (persisted);
        // it will be regenerated fresh from the left the next time you flip.
        state.split = false
      } else {
        // "Flip": the LEFT tree is always the source — (re)generate the right
        // tree from it by Bayes reversal, discarding any prior manual right
        // edits (independence holds only within a split session; re-flipping
        // re-syncs from the source).
        // Drop a selection that lived in the right tree we're about to replace.
        if (state.selected && state.rightRoot && walkFind(state.rightRoot, (n) => n === state.selected)) {
          state.selected = null
        }
        regenerateRight()
        state.split = true
        state.viewRight.scale = 1
        state.viewRight.x = 0
        state.viewRight.y = 0
      }
      // Split mode is a view state, but a flip also (re)generates the right tree
      // and is a single undoable step — commit a snapshot directly.
      pendingCommit = true
      render()
    },

    undo,
    redo,
    canUndo: () => cursor > 0,
    canRedo: () => cursor < history.length - 1,

    setDisplayMode(mode) {
      state.displayMode = mode
      markDirty()
      render()
    },

    setUtilityType(type) {
      // Switching type resets the parameter to that type's sensible default;
      // the user can fine-tune afterward.
      state.utilityFn = defaultUtilityFunction(type)
      markDirty()
      render()
    },

    setUtilityParameter(parameter) {
      state.utilityFn = { ...state.utilityFn, parameter }
      markDirty()
      render()
    },

    selectNode(node) {
      state.selected = node
      render()
    },

    render,
  }

